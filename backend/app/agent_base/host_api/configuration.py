"""Deployment values used across plugin boundaries, without importing Settings."""
from typing import Mapping, Protocol


class PluginConfiguration(Protocol):
    @property
    def llm_api_key(self) -> str: ...
    @property
    def llm_base_url(self) -> str: ...
    @property
    def llm_model_id(self) -> str: ...
    @property
    def strict_production(self) -> bool: ...
    @property
    def agent_design_contract_enabled(self) -> bool: ...
    @property
    def agent_orchestration_enabled(self) -> bool: ...
    @property
    def agent_knowledge_graph_enabled(self) -> bool: ...
    @property
    def agent_memory_recall_top_k(self) -> int: ...
    @property
    def agent_memory_recall_max_tokens(self) -> int: ...
    @property
    def agent_context_soft_limit_tokens(self) -> int: ...
    @property
    def agent_context_hard_limit_tokens(self) -> int: ...
    @property
    def agent_max_run_seconds(self) -> int: ...
    @property
    def agent_max_tool_calls(self) -> int: ...
    @property
    def agent_architecture_scheduling_max_workers(self) -> int: ...
    @property
    def agent_architecture_scheduling_total_tokens(self) -> int: ...
    @property
    def agent_architecture_scheduling_worker_seconds(self) -> float: ...
    @property
    def project_dir(self) -> str: ...
    @property
    def runtime_dir(self) -> str: ...
    @property
    def workspace_roots(self) -> str: ...
    @property
    def plugin_configs(self) -> Mapping[str, Mapping[str, object]]: ...
